// Shared UI helpers: escaping, formatting, badges, modals, toasts and the package diagram.
export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

export function esc(v) {
  if (v === null || v === undefined) return "";
  return String(v).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}
export function icons(root) {
  try { window.lucide.createIcons({ attrs: { "stroke-width": 1.9 }, root: root || document }); } catch (e) { /* offline icon lib missing */ }
}
export function num(v, d = 3) {
  if (v === null || v === undefined || Number.isNaN(v)) return "—";
  return Number(v).toFixed(d);
}
export function autoNum(v, unit = "") {
  if (v === null || v === undefined || Number.isNaN(v)) return "—";
  const a = Math.abs(v);
  const d = a >= 100 ? 1 : a >= 10 ? 2 : 3;
  return `${Number(v).toFixed(d)}${unit ? " " + unit : ""}`;
}
export function timeOf(ms, withMs = false) {
  if (!ms) return "—";
  const d = new Date(ms);
  const t = d.toLocaleTimeString([], { hour12: false });
  return withMs ? `${t}.${String(d.getMilliseconds()).padStart(3, "0")}` : t;
}
export function dateOf(iso) {
  if (!iso) return "—";
  const d = new Date(iso);
  return d.toLocaleString([], { year: "numeric", month: "short", day: "2-digit", hour: "2-digit", minute: "2-digit", hour12: false });
}
export function ago(ms) {
  if (!ms) return "never";
  const s = Math.max(0, (Date.now() - ms) / 1000);
  if (s < 2) return "just now";
  if (s < 60) return `${s.toFixed(0)} s ago`;
  if (s < 3600) return `${(s / 60).toFixed(0)} min ago`;
  return `${(s / 3600).toFixed(1)} h ago`;
}

const STATUS = {
  PASS: ["b-pass", "Pass"], WARN: ["b-warn", "Warning"], FAIL: ["b-fail", "Fail"], INVALID: ["b-fail", "Invalid"],
  NOT_MEASURED: ["b-muted", "Not measured"], NO_REFERENCE: ["b-muted", "No reference"], NOT_APPLICABLE: ["b-muted", "N/A"],
  pass: ["b-pass", "Pass"], warn: ["b-warn", "Warning"], fail: ["b-fail", "Fail"], not_assessed: ["b-muted", "Not assessed"],
};
export function statusBadge(s) {
  const [cls, label] = STATUS[s] || ["b-muted", s || "—"];
  return `<span class="badge ${cls}">${esc(label)}</span>`;
}
export const CLASS_KEYS = {
  "Reference-consistent": "consistent", "Investigation recommended": "investigate",
  "Significant deviation detected": "deviation", "Inconclusive": "inconclusive",
};
export function classBadge(label, key) {
  if (!label) return `<span class="badge b-muted">Not scored</span>`;
  const k = key || CLASS_KEYS[label] || "inconclusive";
  const icon = { consistent: "shield-check", investigate: "search", deviation: "shield-alert", inconclusive: "circle-help" }[k];
  return `<span class="cls cls-${k}"><i data-lucide="${icon}"></i>${esc(label)}</span>`;
}
export function sourceTag(src) {
  if (src === "simulated" || src === "sim") return `<span class="sim-tag" title="Generated by the simulator — not a physical measurement">SIMULATED</span>`;
  if (src === "live") return `<span class="live-tag" title="Physical measurement from the ESP32 test controller">LIVE</span>`;
  return "";
}
export function provTag(ref) {
  if (!ref || !ref.source_type) return "";
  const st = ref.source_type;
  const label = { oem: "OEM datasheet", oem_derived: "OEM-derived", empirical: "Known-good sample", simulated: "Simulated",
    test_criterion: "Test criterion", test_condition: "Test condition" }[st] || st;
  const unv = (st === "oem" || st === "oem_derived") && !ref.verified ? " unverified" : "";
  return `<span class="prov ${esc(st)}${unv}" title="${unv ? "Not verified against the datasheet in this dataset build" : ""}">${esc(label)}${unv ? " · unverified" : ""}</span>`;
}
export function scoreBarClass(s) {
  if (s === null || s === undefined) return "";
  return s >= 80 ? "pass" : s >= 50 ? "warn" : "fail";
}

// ------------------------------------------------------------ toasts & modals
export function toast(msg, kind = "") {
  const box = document.getElementById("toasts");
  const el = document.createElement("div");
  el.className = `toast ${kind}`;
  el.innerHTML = `<i data-lucide="${kind === "error" ? "alert-triangle" : kind === "ok" ? "check-circle-2" : "info"}"></i><span>${esc(msg)}</span>`;
  box.appendChild(el);
  icons(el);
  setTimeout(() => el.remove(), kind === "error" ? 6500 : 3500);
}

export function modal({ title, body, actions = [{ label: "Close", value: null }], wide = false, onMount }) {
  return new Promise((resolve) => {
    const root = document.getElementById("modal-root");
    const back = document.createElement("div");
    back.className = "modal-back";
    back.innerHTML = `<div class="modal ${wide ? "wide" : ""}" role="dialog" aria-modal="true">
      <div class="modal-head"><h3>${esc(title)}</h3><span class="spacer"></span>
        <button class="btn btn-ghost btn-sm" data-x aria-label="Close"><i data-lucide="x"></i></button></div>
      <div class="modal-body">${body}</div>
      <div class="modal-foot">${actions.map((a, i) => `<button class="btn ${a.kind || ""}" data-i="${i}">${esc(a.label)}</button>`).join("")}</div></div>`;
    root.appendChild(back);
    icons(back);
    const close = (v) => { back.remove(); resolve(v); };
    back.addEventListener("click", async (e) => {
      if (e.target === back || e.target.closest("[data-x]")) return close(null);
      const b = e.target.closest("[data-i]");
      if (!b) return;
      const a = actions[+b.dataset.i];
      if (a.handler) {
        try { const r = await a.handler(back); if (r === false) return; close(r === undefined ? a.value : r); }
        catch (err) { toast(err.message, "error"); }
      } else close(a.value);
    });
    if (onMount) onMount(back);
    const first = back.querySelector("input, select, textarea, .modal-foot .btn");
    if (first) first.focus();
  });
}
export const confirmDialog = (title, text, okLabel = "Confirm", danger = false) =>
  modal({ title, body: `<p style="margin:0">${text}</p>`, actions: [{ label: "Cancel", value: false },
    { label: okLabel, value: true, kind: danger ? "btn-danger" : "btn-primary" }] });

// ------------------------------------------------------------ package diagram
const ROLE_COL = { input: "#1769E8", output: "#00A3C4", power: "#DC4545", ground: "#687B91", io: "#5B7BD5", nc: "#B7C3D1" };

export function chipSVG(profile, opts = {}) {
  if (!profile) return "";
  const pins = profile.pins || [];
  if (profile.package_key === "MODULE") return moduleSVG(profile, opts);
  const n = pins.length;
  const half = n / 2;
  const pitch = n > 16 ? 19 : 24;
  const top = 34;
  const H = top + half * pitch + 18;
  const gx = opts.fixture ? 74 : 0;
  const W = 380 + gx * 2;
  const bx = 130 + gx, bw = 120;
  const marking = opts.marking || profile.base_part || "";
  const hl = opts.highlight || {};
  const fx = opts.fixture || {};
  const pinBy = Object.fromEntries(pins.map((p) => [String(p.pin), p]));
  let s = `<svg class="chipdiag" viewBox="0 0 ${W} ${H}" role="img" aria-label="${esc(profile.package)} pinout of ${esc(profile.name)}">`;
  s += `<rect x="${bx}" y="${top - 16}" width="${bw}" height="${half * pitch + 18}" rx="6" fill="#1B2B42"/>`;
  s += `<path d="M${bx + bw / 2 - 13} ${top - 16} a13 13 0 0 0 26 0" fill="#F4F7FB"/>`;
  s += `<circle cx="${bx + 14}" cy="${top + 2}" r="3.5" fill="#33475F"/>`;
  const mk = String(marking).slice(0, 12);
  s += `<text x="${bx + bw / 2}" y="${top - 16 + (half * pitch + 18) / 2}" fill="#C9D5E3" font-size="${mk.length > 9 ? 11 : 13}" text-anchor="middle" transform="rotate(-90 ${bx + bw / 2} ${top - 16 + (half * pitch + 18) / 2})" letter-spacing="1">${esc(mk)}</text>`;
  for (let k = 0; k < n; k++) {
    const left = k < half;
    const idx = left ? k : n - 1 - k;
    const pinNo = k + 1;
    const p = pinBy[String(pinNo)] || { name: String(pinNo), role: "nc" };
    const y = top + idx * pitch;
    const col = ROLE_COL[p.role] || ROLE_COL.nc;
    const x0 = left ? bx - 20 : bx + bw;
    const state = hl[pinNo];
    const fill = state === "high" ? "#16A36A" : state === "low" ? "#9FB0C3" : state === "fail" ? "#DC4545" : "#D5DEE8";
    s += `<rect x="${x0}" y="${y - 5}" width="20" height="10" rx="2" fill="${fill}" stroke="${state ? "none" : "#B9C6D4"}"/>`;
    s += `<text x="${left ? bx + 9 : bx + bw - 9}" y="${y + 4}" font-size="10" fill="#8EA3BB" text-anchor="${left ? "start" : "end"}">${pinNo}</text>`;
    s += `<text x="${left ? bx - 26 : bx + bw + 26}" y="${y + 4}" font-size="11.5" font-weight="600" fill="${col}" text-anchor="${left ? "end" : "start"}">${esc(p.name)}</text>`;
    const g = fx[String(pinNo)];
    if (opts.fixture) {
      const gxpos = left ? bx - 92 : bx + bw + 92;
      const has = g !== undefined && g !== null && g !== "";
      s += `<text x="${gxpos}" y="${y + 4}" font-size="10.5" fill="${has ? "#172B45" : "#C2CDDA"}" text-anchor="${left ? "end" : "start"}">${has ? "GPIO" + esc(g) : "—"}</text>`;
    }
  }
  s += `</svg>`;
  return s;
}

function moduleSVG(profile, opts) {
  const pins = profile.pins || [];
  const H = 40 + pins.length * 26;
  let s = `<svg class="chipdiag" viewBox="0 0 380 ${H}" role="img" aria-label="Module signals">`;
  s += `<rect x="150" y="14" width="140" height="${H - 28}" rx="6" fill="#1B2B42"/><rect x="160" y="24" width="120" height="40" rx="3" fill="#33475F"/>`;
  s += `<text x="220" y="49" fill="#C9D5E3" font-size="12" text-anchor="middle">${esc(profile.base_part || "MODULE")}</text>`;
  pins.forEach((p, i) => {
    const y = 84 + i * 22;
    const col = ROLE_COL[p.role] || ROLE_COL.nc;
    s += `<rect x="130" y="${y - 5}" width="20" height="10" rx="2" fill="#D5DEE8" stroke="#B9C6D4"/>`;
    s += `<text x="122" y="${y + 4}" font-size="11.5" font-weight="600" fill="${col}" text-anchor="end">${esc(p.name)}</text>`;
    if (opts.fixture && opts.fixture[p.pin] != null) s +=`<text x="40" y="${y + 4}" font-size="10.5" fill="#172B45">GPIO${esc(opts.fixture[p.pin])}</text>`;
  });
  return s + "</svg>";
}

export function roleLegend() {
  return `<div class="legend-inline">${[["input", "Input"], ["output", "Output"], ["power", "Supply"], ["ground", "Ground"], ["io", "I/O"]]
    .map(([k, l]) => `<span><i style="background:${ROLE_COL[k]}"></i>${l}</span>`).join("")}</div>`;
}

